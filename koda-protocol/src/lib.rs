//! The protocol every Koda client speaks: JSON-RPC 2.0 requests, responses
//! and notifications, and the types they carry.
//!
//! Codex's app-server protocol is the model (`codex-rs/app-server-protocol`):
//! a connection opens with `initialize`, methods are named `noun/verb`, and
//! fields are camelCase. Koda differs in three ways. Messages keep
//! `"jsonrpc": "2.0"`, so standard JSON-RPC libraries work unmodified. A
//! conversation is a session, not a thread. And the catalog is Koda's own,
//! much smaller one.
//!
//! The protocol grows with the code that serves it: a method or
//! notification is added in the change that first sends or answers it.
//!
//! ## Schema
//!
//! `docs/src/protocol-schema.json` is generated by [`schema`], and a test
//! fails when it goes stale. Refresh it with:
//!
//! ```text
//! KODA_UPDATE_PROTOCOL_SCHEMA=1 cargo test -p koda-protocol --lib schema
//! ```

pub mod initialize;
mod request;
pub mod rpc;
pub mod state;

pub use request::{ClientRequest, DecodeError, Method, encode, methods};

use schemars::generate::SchemaSettings;
use serde_json::{Value, json};

/// The protocol's version, sent in the `initialize` response. Version 1
/// was `stream-json`, the output-only format this protocol replaces.
pub const PROTOCOL_VERSION: u32 = 2;

/// The protocol as one JSON Schema document: every message shape, and
/// for each method its parameters and result.
pub fn schema() -> Value {
    let mut generator = SchemaSettings::draft2020_12().into_generator();
    let message = generator.subschema_for::<rpc::Message>();
    let methods = request::method_schemas(&mut generator);
    let definitions = generator.take_definitions(true);
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "Koda client protocol",
        "protocolVersion": PROTOCOL_VERSION,
        "message": message,
        "methods": methods,
        "$defs": definitions,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    const SCHEMA_PATH: &str = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../docs/src/protocol-schema.json"
    );

    /// Fails when a protocol type changes and the checked-in schema doesn't.
    #[test]
    fn schema_file_is_current() {
        let schema = schema();
        if std::env::var_os("KODA_UPDATE_PROTOCOL_SCHEMA").is_some() {
            let text = serde_json::to_string_pretty(&schema).unwrap();
            std::fs::write(SCHEMA_PATH, text + "\n").unwrap();
            return;
        }
        let text = std::fs::read_to_string(SCHEMA_PATH).unwrap();
        let checked_in: Value = serde_json::from_str(&text).unwrap();
        assert_eq!(
            checked_in, schema,
            "docs/src/protocol-schema.json is stale. Refresh it with \
             KODA_UPDATE_PROTOCOL_SCHEMA=1 cargo test -p koda-protocol --lib schema"
        );
    }

    #[test]
    fn the_schema_lists_every_method() {
        let schema = schema();
        let table = schema["methods"].as_object().unwrap();
        let listed: Vec<&str> = table.keys().map(String::as_str).collect();
        assert_eq!(listed.len(), ClientRequest::METHODS.len());
        for method in ClientRequest::METHODS {
            assert!(
                table.contains_key(*method),
                "{method} missing from the schema"
            );
        }
    }
}
